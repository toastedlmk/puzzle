function p(
  title,
  prompt,
  type,
  content,
  answers,
  hint1,
  hint2,
  explanation,
  extra = {},
) {
  const list = Array.isArray(answers) ? answers : [answers];
  return {
    title,
    prompt,
    type,
    content,
    answers: list,
    hints: [hint1, hint2, `The answer is “${list[0]}”.`],
    explanation,
    ...extra,
  };
}

